export type TranslationKey = keyof typeof translations;
export type Dict = typeof translations;

export const t = (section: TranslationKey, key: string, lang: Language): string => {
  const sectionObj = translations[section] as unknown as Record<string, Record<Language, string>>;
  const entry = sectionObj?.[key];
  if (!entry) return key;
  return entry[lang] ?? entry.en ?? key;
};
